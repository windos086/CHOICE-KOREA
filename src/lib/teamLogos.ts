export function findLeagueLogo(leagueName: string): string | null {
  if (!leagueName) return null;
  const name = leagueName.replace(/\s+/g, '').toLowerCase();
  for (const [key, url] of Object.entries(LEAGUE_LOGOS)) {
    const cleanKey = key.replace(/\s+/g, '').toLowerCase();
    if (name.includes(cleanKey)) {
      return url;
    }
  }
  return null;
}

