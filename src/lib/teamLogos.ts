export function findTeamLogo(teamName: string): string | null {
  if (!teamName) return null;
  const name = teamName.replace(/\s+/g, '').toLowerCase();
  for (const [key, url] of Object.entries(TEAM_LOGOS)) {
    const cleanKey = key.replace(/\s+/g, '').toLowerCase();
    if (name.includes(cleanKey) || cleanKey.includes(name)) {
      return url;
    }
  }
  return null;
}

export function findCountryFlag(teamName: string): string | null {
  if (!teamName) return null;
  const name = teamName.replace(/\s+/g, '').toLowerCase();
  for (const [key, emoji] of Object.entries(COUNTRY_FLAGS)) {
    const cleanKey = key.replace(/\s+/g, '').toLowerCase();
    if (name.includes(cleanKey)) {
      return emoji;
    }
  }
  return null;
}

export function findCountryFlagUrl(teamName: string): string | null {
  if (!teamName) return null;
  const name = teamName.replace(/\s+/g, '').toLowerCase();
  for (const [key, code] of Object.entries(COUNTRY_CODES)) {
    const cleanKey = key.replace(/\s+/g, '').toLowerCase();
    if (name.includes(cleanKey)) {
      return `https://flagcdn.com/w40/${code}.png`;
    }
  }
  return null;
}

